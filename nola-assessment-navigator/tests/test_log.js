// Writes docs/chatbot-test-log.md: every test question with the chatbot's COMPLETE answer, word for word, plus a
// screenshot. Run from nola-assessment-navigator/ with a server (python3 -m http.server 8765):
//   node tests/chatbot_eval.js && node tests/test_log.js
const fs = require("fs");
const path = require("path");
let chromium;
try { ({ chromium } = require("playwright")); } catch (e) { ({ chromium } = require("/opt/node-tools/node_modules/playwright")); }
const ROOT = path.join(__dirname, "..");
const SHOTS = "docs/screenshots/log";
const URL = process.argv[2] || "http://localhost:8765/index.html";

// Part 1: the five sample questions, plus the question the Part 1 bot couldn't answer.
const GENERAL = [
  { q: "How is my property tax bill calculated?", expect: "Formula; $300,000 example with 121.20 citywide mills + levee; police/fire mills without homestead; sources." },
  { q: "How do I apply for the homestead exemption?", expect: "Amount, own-and-occupy rule, documents, a note that the instructions are dated and should be confirmed; contacts." },
  { q: "What does the 2027 reassessment mean for me?", expect: "2024–27 values as of Jan. 1, 2023 (official); the 2027 roll is not a reappraisal; next one inferred for 2028; appeal status for today." },
  { q: "Should I appeal? My house is worth less than what the Assessor says.", expect: "Refuses advice, then gives the appeal steps, today's deadline status and human contacts." },
  { q: "Can I pay my property taxes in installments?", expect: "No formal installment plan; partial payments in person or by mail; 1% a month interest; sourced." },
  { q: "I live in half of a double. Do I get the homestead exemption?", expect: "What the law says (owned and occupied, one per person, ownership share), and a plain \"I don't know\" on how the rented half is treated; contacts." }
];
// The in-class demo: a general question, a lookup, the two together, and a refusal.
const DEMO = [
  { find: "1205 St. Charles Ave, Apt 607", expect: "One record; property card with recorded values." },
  { q: "How much tax will I pay?", expect: "Leads with the next bill (2027 roll), then 2026; calculated check; roll-forward range; labeled recorded / calculated / explanation." },
  { q: "How do I apply for the homestead exemption?", expect: "General answer plus a \"Your property\" panel showing the homestead already on this record." },
  { q: "How does my property compare to others in my area?", expect: "Layer 3: distribution of similar parcels; says it doesn't mean the value is too high or low." },
  { q: "Should I appeal my assessment?", expect: "Refuses advice; shows the record and human contacts." }
];
// Addresses of parcels whose record reveals a disability or age-based benefit are withheld (CLAUDE.md §4 rule 9).
const WITHHELD = { 4: "a home with an assessment freeze", 5: "a home with a full disabled-veteran exemption", 7: "the frozen home from test 4" };

(async () => {
  const exe = process.env.CHROME || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome";
  const b = await chromium.launch(fs.existsSync(exe) ? { executablePath: exe } : {});
  fs.mkdirSync(path.join(ROOT, SHOTS), { recursive: true });
  const newPage = async () => {
    const p = await b.newPage({ viewport: { width: 820, height: 1000 }, deviceScaleFactor: 2 });
    await p.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
    await p.goto(URL); await p.waitForTimeout(300);
    await p.addStyleTag({ content: ".ask{position:static !important}.selected{position:static !important}" });
    return p;
  };
  // Screenshot the last question and its answer together, whatever the page length.
  const shot = async (p, name) => {
    const pos = await p.evaluate(() => {
      const u = [...document.querySelectorAll(".msg.user")].pop().getBoundingClientRect();
      const m = [...document.querySelectorAll(".msg.bot")].pop().getBoundingClientRect();
      return { y: u.top + scrollY, h: m.bottom - u.top };
    });
    const file = `${SHOTS}/${name}.png`;
    await p.screenshot({ path: path.join(ROOT, file), fullPage: true, clip: { x: 0, y: Math.max(0, pos.y - 10), width: 820, height: pos.h + 20 } });
    return file;
  };
  const answerText = async p => (await p.locator(".msg.bot").last().innerText()).trim();
  const quote = t => t.split("\n").map(l => "> " + l).join("\n");

  const out = [];
  out.push(`# Chatbot test log: complete answers

Generated by \`node tests/test_log.js\` on ${new Date().toISOString().slice(0, 10)} from the code in this repo (the same code as the live site).
Each entry shows what was typed, what a correct answer needs, and the chatbot's **complete answer, word for word**,
followed by a screenshot. Nothing is summarized. Source tags like [S11] are links in the page; the "Sources" list
under each answer names them.

Contents: A. the five Part 1 sample questions, plus the "half of a double" question the Part 1 bot couldn't answer ·
B. the ten Part 2 property questions, checked against the raw roll · C. the demo conversation (general question,
lookup, the layers together, refusal).
`);

  out.push("## A. General questions (Part 1 sample questions, re-run)\n");
  for (const [i, c] of GENERAL.entries()) {
    const p = await newPage();
    await p.fill("#q", c.q); await p.click("#ask button"); await p.waitForTimeout(500);
    const t = await answerText(p);
    const f = await shot(p, `a${i + 1}`);
    out.push(`### A${i + 1}. "${c.q}"\n\n**A correct answer needs:** ${c.expect}\n\n**Complete answer:**\n\n${quote(t)}\n\n![Screenshot of answer A${i + 1}](${f.replace("docs/", "")})\n`);
    console.log("A" + (i + 1), t.length, "chars");
    await p.close();
  }

  out.push("## B. Property questions (Part 2 test set)\n\nExpected values were pulled from the raw 2026 roll and the state's millage files before the test ran (`tests/expected_from_raw.py`). A test passes only if every expected value appears in the answer.\n");
  const rows = JSON.parse(fs.readFileSync(path.join(__dirname, "chatbot_eval_results.json"), "utf8"));
  for (const r of rows) {
    const hide = WITHHELD[r.n];
    let full = r.full || r.got;
    if (hide) full = full.split("\n").map((l, k) => (k === 0 ? "[address and parcel ID withheld]" : l)).join("\n");
    out.push(`### B${r.n}. ${r.prop ? `Property: ${hide ? `*${hide} (address withheld)*` : `"${r.prop}"`} · Question: "${r.q}"` : `Search: "${r.q}"`}\n\n**Expected (from the raw roll):** ${r.expect}\n\n**Result:** ${r.ok ? "✅ Pass" : "❌ Fail, missing: " + r.missing.join(", ")}\n\n**Complete answer:**\n\n${quote(full)}\n\n${hide ? "*Screenshot withheld: this record shows a benefit tied to age or disability, so the address isn't published.*" : `![Screenshot of answer B${r.n}](${r.shot.replace("docs/", "")})`}\n`);
  }

  out.push("## C. Demo conversation (one session, in order)\n");
  const p = await newPage();
  for (const [i, c] of DEMO.entries()) {
    if (c.find) {
      await p.fill("#addr", c.find); await p.click("#find button");
      await p.waitForSelector(".msg.bot .pick:not([disabled])", { timeout: 15000 });
      const list = await answerText(p);
      await p.locator(".msg.bot").last().locator(".pick").first().click(); await p.waitForTimeout(500);
      const card = await answerText(p);
      const f = await shot(p, `c${i + 1}`);
      out.push(`### C${i + 1}. Find your property: "${c.find}"\n\n**A correct answer needs:** ${c.expect}\n\n**Complete answer (search result, then the record after picking it):**\n\n${quote(list)}\n\n${quote(card)}\n\n![Screenshot of step C${i + 1}](${f.replace("docs/", "")})\n`);
    } else {
      await p.fill("#q", c.q); await p.click("#ask button"); await p.waitForTimeout(500);
      const t = await answerText(p);
      const f = await shot(p, `c${i + 1}`);
      out.push(`### C${i + 1}. "${c.q}"\n\n**A correct answer needs:** ${c.expect}\n\n**Complete answer:**\n\n${quote(t)}\n\n![Screenshot of answer C${i + 1}](${f.replace("docs/", "")})\n`);
    }
    console.log("C" + (i + 1));
  }
  await p.close();
  await b.close();
  fs.writeFileSync(path.join(ROOT, "docs/chatbot-test-log.md"), out.join("\n"));
  console.log("wrote docs/chatbot-test-log.md");
})();
