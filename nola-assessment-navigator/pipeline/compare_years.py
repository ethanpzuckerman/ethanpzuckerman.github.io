"""Compare two Orleans Parish rolls parcel by parcel (e.g. 2025 vs 2026).

Run from nola-assessment-navigator/:
  python3 pipeline/compare_years.py data/raw/<2025 roll>.csv data/raw/Orleans_Parish_2026_LTC_Expanded_Real_Estate_Roll.csv
Joins on Parcel ID (the same as Tax Bill # in the 2026 file), never on address, and reports
parcels found in only one year (new, split, merged or retired parcels) instead of guessing.
Writes docs/year-comparison.md and data/processed/value_changes.csv.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
KEY = "Parcel ID(s)"
VALUES = ["Total Market Value", "Total Assessed Value", "Homestead Exemption Amount", "Taxable Assessed Value"]


def load(path):
    df = pd.read_csv(path, dtype=str, encoding="utf-8-sig", low_memory=False)
    missing = [c for c in [KEY, "Property Address(es)", *VALUES] if c not in df.columns]
    if missing:
        raise SystemExit(f"{path}: missing columns {missing}. Map them before comparing.")
    for c in VALUES:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    year = df["Tax Year"].iloc[0] if "Tax Year" in df.columns else Path(path).stem
    return df[[KEY, "Property Address(es)", *VALUES]], str(year)


def main(a, b):
    old, y0 = load(a)
    new, y1 = load(b)
    # Fixed suffixes so two files with the same Tax Year still compare cleanly.
    m = old.merge(new, on=KEY, how="outer", suffixes=("_old", "_new"), indicator=True)
    both = m[m["_merge"] == "both"].copy()
    for c in VALUES:
        both[f"{c} change"] = both[f"{c}_new"] - both[f"{c}_old"]
    tmv = "Total Market Value change"
    both["market_pct"] = both[tmv] / both["Total Market Value_old"].where(both["Total Market Value_old"] > 0)
    out = ROOT / "data/processed/value_changes.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    both.drop(columns="_merge").to_csv(out, index=False)
    only0, only1 = (m["_merge"] == "left_only").sum(), (m["_merge"] == "right_only").sum()
    addr_changed = (both["Property Address(es)_old"] != both["Property Address(es)_new"]).sum()
    md = f"""# {y0} vs {y1} roll comparison

Joined on **{KEY}**. Generated by `pipeline/compare_years.py`.

| | Parcels |
|---|---|
| In both years | {len(both):,} |
| Only in {y0} (retired, merged or renumbered) | {only0:,} |
| Only in {y1} (new, split or renumbered) | {only1:,} |
| Same parcel ID, address text changed | {addr_changed:,} |
| Market value unchanged | {(both[tmv] == 0).sum():,} |
| Market value up | {(both[tmv] > 0).sum():,} |
| Market value down | {(both[tmv] < 0).sum():,} |
| Median change among parcels that changed | {both.loc[both[tmv] != 0, 'market_pct'].median():.1%} |

Parcels in only one year can't be compared by ID, so the app says it doesn't know rather than
guessing from the address.
"""
    (ROOT / "docs/year-comparison.md").write_text(md)
    print(md)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
